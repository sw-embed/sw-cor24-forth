#!/usr/bin/env bash
# build-forth.sh — regenerate forth.s from forth-core.s and forth-uart.s.
#
#   scripts/build-forth.sh            write forth.s
#   scripts/build-forth.sh --check    fail if the checked-in forth.s is stale
#
# forth.s is the kernel every consumer runs: the web demo compiles it in by
# path, the FPGA build assembles it, the regression suite exercises it. It is
# generated and checked in, because none of those consumers can concatenate.
# The core is target-independent; the UART layer is the stand-alone board.
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/.." && pwd)"
OUT="$ROOT/forth.s"

generate() {
  printf '; forth.s — GENERATED by scripts/build-forth.sh from forth-core.s and\n'
  printf '; forth-uart.s; do not edit. Edit those and rerun the script.\n'
  printf ';\n'
  cat "$ROOT/forth-core.s" "$ROOT/forth-uart.s"
}

if [ "${1:-}" = "--check" ]; then
  if diff -q <(generate) "$OUT" >/dev/null; then
    echo "forth.s is current"
  else
    echo "forth.s is stale: run scripts/build-forth.sh" >&2
    exit 1
  fi
else
  generate > "$OUT"
  echo "wrote $OUT ($(wc -l < "$OUT" | tr -d ' ') lines)"
fi
