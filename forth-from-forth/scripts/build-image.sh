#!/usr/bin/env bash
# build-image.sh — generate forth-from-forth/kernel.s, entirely from Forth.
#
#   scripts/build-image.sh            regenerate kernel.s
#   scripts/build-image.sh --check    fail if kernel.s is stale
#
# The cross-compiler runs in the emulator on forth-from-forth's own kernel
# (a fixed point; see HOST below) and prints kernel.s over the UART:
#   1. core/prims-asm.fth, in the assembler vocabulary of compiler/xcomp.fth,
#      prints the primitive section (start-up code, NEXT/DOCOL, primitives,
#      UART layer, variables) and names the newest assembly entry;
#   2. XC-COMPILE-SOURCE compiles the five core tiers (minus the QUIT-VECTOR
#      hand-off at the end of highlevel.fth, which only the UART bootstrap
#      needed) into dictionary entries linked onto that entry;
#   3. at XC-END the compiler prints fff_latest (LATEST at boot), the
#      start-up thread that stores the Forth QUIT in QUIT-VECTOR and runs
#      it, and dict_end (HERE at boot).
# No assembly template is read. scripts/dead-code.py then checks that every
# block of the result is reachable.
set -euo pipefail
set -f
HERE="$(cd "$(dirname "$0")" && pwd)"
FFF="$(cd "$HERE/.." && pwd)"
ROOT="$(cd "$FFF/.." && pwd)"
# The compiler runs on forth-from-forth's own committed kernel, which
# already holds the core, so nothing but the compiler is streamed in. To
# restart the chain from the hand-written phase-3 kernel (if kernel.s is
# ever broken), set XC_HOST=forth-on-forthish/kernel.s: any other host gets
# the five core tiers streamed in first.
HOST="${XC_HOST:-$FFF/kernel.s}"
if [ "$(cd "$(dirname "$HOST")" && pwd)/$(basename "$HOST")" = "$FFF/kernel.s" ]; then
  HOST_CORE=""
else
  HOST_CORE="$(cat "$FFF"/core/{runtime,minimal,lowlevel,midlevel,highlevel}.fth)"
fi
OUT="$FFF/kernel.s"
WORK="$(mktemp -d -t build-image)"; trap 'rm -rf "$WORK"' EXIT
cd "$ROOT"

cat "$FFF"/core/{runtime,minimal,lowlevel,midlevel,highlevel}.fth \
  | grep -v -x -e "' QUIT QUIT-VECTOR !" -e "QUIT" > "$WORK/core.fth"

INPUT="$(
  [ -n "$HOST_CORE" ] && printf '%s\n' "$HOST_CORE"
  cat "$FFF/compiler/xcomp.fth"
  echo "1 xc-bye !"
  echo "XC-KERNEL-BEGIN"
  cat "$FFF/core/prims.fth"
  cat "$FFF/core/prims-asm.fth"
  echo "XC-COMPILE-SOURCE"
  cat "$WORK/core.fth"
  echo "XC-END"
)
"
"$ROOT/scripts/run-kernel.sh" "$HOST" -u "$INPUT" --speed 0 -n 6000000000 2>&1 \
  | sed -n '/^UART output:/,$p' \
  | sed -n '/^!!BEGIN-KERNEL!!$/,/^!!END-KERNEL!!$/p' \
  | sed '1d;$d' \
  | grep -v '^ ok$' > "$WORK/body.s" || true

if ! grep -q '^dict_end:$' "$WORK/body.s"; then
  echo "build-image: the compiler did not finish (no dict_end); last lines:" >&2
  tail -5 "$WORK/body.s" >&2; exit 1
fi
if grep -q '^; ?' "$WORK/body.s"; then
  echo "build-image: unresolved tokens:" >&2; grep '^; ?' "$WORK/body.s" >&2; exit 1
fi
{
  echo "; GENERATED by forth-from-forth/scripts/build-image.sh -- do not edit."
  echo "; Primitives: core/prims-asm.fth; dictionary: core/*.fth; both written"
  echo "; out by the cross-compiler compiler/xcomp.fth, which is Forth."
  echo ";"
  cat "$WORK/body.s"
} > "$WORK/kernel.s"

python3 "$HERE/dead-code.py" "$WORK/kernel.s" > "$WORK/dead.txt"
if ! head -1 "$WORK/dead.txt" | grep -q 'dead 0 '; then
  echo "build-image: unreachable code in the generated kernel:" >&2; cat "$WORK/dead.txt" >&2; exit 1
fi

if [ "${1:-}" = "--check" ]; then
  if cmp -s "$WORK/kernel.s" "$OUT"; then echo "kernel.s is current"; else echo "kernel.s is stale: run scripts/build-image.sh" >&2; exit 1; fi
else
  cp "$WORK/kernel.s" "$OUT"
  echo "build-image: wrote $OUT ($(wc -l < "$OUT" | tr -d ' ') lines, $(grep -c '^fff_e' "$OUT") compiled definitions)" >&2
fi
